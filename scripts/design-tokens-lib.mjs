// Shared, dependency-free parsing/generation logic for design-system.md.
// Used by both scripts/sync-design-tokens.mjs (build-time) and vite.config.ts (dev-time watcher).

const BLOCK_KEYS = ['colors', 'typography', 'radii', 'shadows'];

function extractBlockLines(sourceLines, key) {
  const startMarker = `<!-- tokens:${key} -->`;
  const endMarker = `<!-- /tokens:${key} -->`;
  const startIdx = sourceLines.findIndex((line) => line.trim() === startMarker);
  const endIdx = sourceLines.findIndex((line) => line.trim() === endMarker);

  if (startIdx === -1 || endIdx === -1) {
    throw new Error(`design-system.md: missing "${key}" tokens block (expected ${startMarker} ... ${endMarker})`);
  }
  if (endIdx <= startIdx) {
    throw new Error(`design-system.md: "${key}" tokens block end marker appears before or at its start marker`);
  }

  return sourceLines.slice(startIdx + 1, endIdx).map((text, i) => ({ text, lineNumber: startIdx + 2 + i }));
}

function parseBlock(sourceLines, key, seenNames) {
  const blockLines = extractBlockLines(sourceLines, key);
  const tableLines = blockLines.filter((line) => line.text.trim().startsWith('|'));

  if (tableLines.length < 2) {
    throw new Error(
      `design-system.md: "${key}" tokens block has no table (need a header row, a separator row, and at least one data row)`,
    );
  }

  const dataLines = tableLines.slice(2);
  if (dataLines.length === 0) {
    throw new Error(`design-system.md: "${key}" tokens block has a table but no data rows`);
  }

  const rows = [];
  for (const { text, lineNumber } of dataLines) {
    const parts = text.trim().split('|');
    const cells = parts.slice(1, -1).map((cell) => cell.trim());

    if (cells.length !== 3) {
      throw new Error(
        `design-system.md: malformed row in "${key}" block at line ${lineNumber}: expected 3 columns (Token | Value | Usage), found ${cells.length}`,
      );
    }

    const [rawToken, rawValue, rawUsage] = cells;

    const tokenMatch = /^`(--[a-z0-9-]+)`$/.exec(rawToken);
    if (!tokenMatch) {
      throw new Error(
        `design-system.md: malformed token name in "${key}" block at line ${lineNumber}: expected a backticked CSS variable like \`--color-primary\`, found "${rawToken}"`,
      );
    }

    const valueMatch = /^`([^`]+)`$/.exec(rawValue);
    if (!valueMatch) {
      throw new Error(
        `design-system.md: malformed value in "${key}" block at line ${lineNumber}: expected a backticked value, found "${rawValue}"`,
      );
    }

    const name = tokenMatch[1];
    const value = valueMatch[1];
    // Usage is free prose and may legitimately contain inline code spans
    // (e.g. "...using `--color-primary`") — only trim surrounding whitespace,
    // don't strip backticks the way we do for the strictly-wrapped Token/Value cells.
    const usage = rawUsage.trim();

    if (!usage) {
      throw new Error(`design-system.md: missing usage description in "${key}" block at line ${lineNumber}`);
    }
    if (seenNames.has(name)) {
      throw new Error(`design-system.md: duplicate token "${name}" (already defined earlier in the file) at line ${lineNumber}`);
    }
    seenNames.add(name);

    rows.push({ name, value, usage });
  }

  return rows;
}

export function parseDesignSystemMarkdown(source) {
  const sourceLines = source.split('\n');
  const seenNames = new Set();
  const tokens = {};
  for (const key of BLOCK_KEYS) {
    tokens[key] = parseBlock(sourceLines, key, seenNames);
  }
  return tokens;
}

const GENERATED_HEADER =
  'AUTO-GENERATED by scripts/sync-design-tokens.mjs from design-system.md — DO NOT HAND-EDIT.\n' +
  'Edit design-system.md instead: changes sync automatically while `npm run dev` is running,\n' +
  'and on every `npm run build`.';

// CSS comments can't contain the literal sequence "*/" — guard against it
// even though our own design-system.md never uses it, since usage text is free prose.
const escapeCssComment = (text) => text.replace(/\*\//g, '* /');

export function renderTokensCss(tokens) {
  const sections = [
    ['Colors', tokens.colors],
    ['Typography', tokens.typography],
    ['Radii', tokens.radii],
    ['Shadows', tokens.shadows],
  ];
  const body = sections
    .map(([title, list]) => {
      const lines = list.map((t) => `  ${t.name}: ${t.value}; /* ${escapeCssComment(t.usage)} */`).join('\n');
      return `  /* ${title} */\n${lines}`;
    })
    .join('\n\n');

  return `/* ${GENERATED_HEADER.split('\n').join('\n   ')} */\n\n:root {\n${body}\n}\n`;
}

export function renderTokensTs(tokens) {
  const array = (list) => JSON.stringify(list, null, 2);

  return `// ${GENERATED_HEADER.split('\n').join('\n// ')}

export interface DesignToken {
  name: string;
  value: string;
  usage: string;
}

export const colorTokens: DesignToken[] = ${array(tokens.colors)};

export const typographyTokens: DesignToken[] = ${array(tokens.typography)};

export const radiusTokens: DesignToken[] = ${array(tokens.radii)};

export const shadowTokens: DesignToken[] = ${array(tokens.shadows)};
`;
}
